#!/usr/bin/env node
// Regenerates one icon set's `<Set>Icons` global from ui/icons/<set>/*.svg
// into ui/icons/<set>.slint, entirely -- unlike ui/icons.slint (the `Icon`
// component plus one `export { ... } from "icons/<set>.slint";` line per
// set), nothing in a generated set file is hand-maintained, so this just
// overwrites it rather than patching a block inside it.
//
// Usage: node gen-icons-slint.js <set>   (e.g. `tabler`)
// Run after vendor-icons.sh (or whatever vendors that set's svgs).

const fs = require("fs");
const path = require("path");

const set = process.argv[2];
if (!set) {
  console.error("usage: gen-icons-slint.js <set>");
  process.exit(1);
}

const crateDir = path.resolve(__dirname, "..");
const iconsDir = path.join(crateDir, "ui", "icons", set);
const outFile = path.join(crateDir, "ui", "icons", `${set}.slint`);
const globalName = set.charAt(0).toUpperCase() + set.slice(1) + "Icons";

if (!fs.existsSync(iconsDir)) {
  console.error(`no such icon set directory: ${iconsDir}`);
  process.exit(1);
}

const names = fs
  .readdirSync(iconsDir)
  .filter((f) => f.endsWith(".svg"))
  .map((f) => f.slice(0, -4))
  .sort();

if (names.length === 0) {
  console.error(`no .svg files found in ${iconsDir}`);
  process.exit(1);
}

const text =
  `// Generated by scripts/gen-icons-slint.js ${set} -- do not hand-edit.\n` +
  `export global ${globalName} {\n` +
  names
    .map(
      (name) =>
        `    out property <image> ${name}: @image-url("${set}/${name}.svg");`,
    )
    .join("\n") +
  "\n}\n";

fs.writeFileSync(outFile, text);
console.log(`wrote ${names.length} icons into ${outFile} (${globalName})`);

//! アプリ全体で共有する、カテゴリ的な値(idなど)向けの配色ロジック。
//!
//! 元はcettila-view-graph側にのみ存在していたが、他のview(将来的な
//! ノート/タグの色分け等)からも同じ配色ルールを再利用できるよう、
//! ここに一元化してある。

/// HSV(h: 0..360, s/v: 0..1) から RGB(0..1) への簡易変換。
fn hsv_to_rgb(h: f32, s: f32, v: f32) -> [f32; 3] {
    let c = v * s;
    let h_prime = (h % 360.0) / 60.0;
    let x = c * (1.0 - (h_prime % 2.0 - 1.0).abs());
    let (r1, g1, b1) = match h_prime as u32 {
        0 => (c, x, 0.0),
        1 => (x, c, 0.0),
        2 => (0.0, c, x),
        3 => (0.0, x, c),
        4 => (x, 0.0, c),
        _ => (c, 0.0, x),
    };
    let m = v - c;
    [r1 + m, g1 + m, b1 + m]
}

/// `index`から一意に決まる、カラフルな配色を返す(0..1のRGB)。
///
/// 黄金角(137.5°)ずつhueをずらすことで、隣接するindex同士は勿論、
/// 個数が多くなっても色がかぶりにくい(golden-angle low-discrepancy
/// sequence)。固定スウォッチと違い任意の個数に対応できるため、
/// ノード数が変動するグラフ描画のような用途に向く。
/// s/vはダーク背景(#1e1e1e相当)を前提にした値で固定している。
pub fn categorical_color(index: u64) -> [f32; 3] {
    let hue = (index as f32 * 137.5) % 360.0;
    hsv_to_rgb(hue, 0.65, 0.95)
}
